import { Platform } from 'react-native';
import { File, Paths } from 'expo-file-system';
import type { ReportPeriod, ReportRequest } from '../types/api';
import { API_BASE_URL, apiRequest, getAccessToken, getFreshAccessToken } from './api';

export type RequestReportInput = {
  studentUserId: string;
  period: ReportPeriod;
  includeCardPurchases: boolean;
  includeTransfers: boolean;
  includeWithdrawals: boolean;
  includeFlagged: boolean;
  includePending: boolean;
  includeSavings: boolean;
};

export async function requestReport(input: RequestReportInput): Promise<ReportRequest> {
  return apiRequest<ReportRequest>('/reports/request', { method: 'POST', body: input });
}

export async function getMyReports(): Promise<ReportRequest[]> {
  return apiRequest<ReportRequest[]>('/reports/mine');
}

async function downloadWithToken(reportId: string, token: string | null): Promise<File> {
  const destination = new File(Paths.document, `eduwallet-report-${reportId}.pdf`);
  return File.downloadFileAsync(`${API_BASE_URL}/reports/${reportId}/download`, destination, {
    headers: token ? { Authorization: `Bearer ${token}` } : undefined,
    idempotent: true,
  });
}

// expo-file-system's File/Directory API has no web implementation — ExpoFileSystem.FileSystemFile
// is stubbed on web with a bare constructor and no validatePath(), so `new File(...)` throws
// "this.validatePath is not a function" the instant it runs there. Web has no app filesystem to
// download into anyway, so the browser's own download mechanism (an object URL + a clicked
// <a download>) stands in for it on that platform.
async function downloadOnWeb(reportId: string, token: string | null): Promise<string> {
  const res = await fetch(`${API_BASE_URL}/reports/${reportId}/download`, {
    headers: token ? { Authorization: `Bearer ${token}` } : undefined,
  });
  if (!res.ok) {
    throw new Error(`Failed to download report (status ${res.status})`);
  }
  const blob = await res.blob();
  const objectUrl = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = objectUrl;
  link.download = `eduwallet-report-${reportId}.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
  return objectUrl;
}

// Downloads the report PDF and returns a local URI (file:// on native, blob: on web) ready to
// be passed to Sharing.shareAsync (react-native-paper has no built-in PDF viewer). This bypasses
// apiRequest's fetch wrapper to send the token as a plain header, so it doesn't get apiRequest's
// automatic refresh-on-401 — a report is generated by an admin and often downloaded well after
// the 15-minute access token has expired (CLAUDE.md), so that retry has to be reproduced here.
export async function downloadReportPdf(reportId: string): Promise<string> {
  const token = await getAccessToken();
  try {
    if (Platform.OS === 'web') {
      return await downloadOnWeb(reportId, token);
    }
    const file = await downloadWithToken(reportId, token);
    return file.uri;
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    if (!message.includes('401')) {
      throw err;
    }
    const freshToken = await getFreshAccessToken();
    if (!freshToken) {
      throw err;
    }
    if (Platform.OS === 'web') {
      return downloadOnWeb(reportId, freshToken);
    }
    const file = await downloadWithToken(reportId, freshToken);
    return file.uri;
  }
}
